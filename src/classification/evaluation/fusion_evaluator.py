"""Leakage-safe nested cross-validation evaluator for late-fusion classifiers.

For each model family: train sample-level base classifiers per basis (stride,
epoch), pool their per-sample probabilities to a participant score, then combine
the stride/epoch participant scores with each fusion strategy. Cross-validation
splits PARTICIPANTS (not samples) so a participant never appears in both train
and test. Fusion strategies that require training are fit on out-of-fold base
scores generated by an inner participant-level split.
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Dict, List, Optional, Tuple

import numpy as np
from sklearn.metrics import confusion_matrix

from src.classification.data.classification_dataset import (
    BasisSampleDataset,
    ClassificationDataset,
)
from src.classification.evaluation.cross_validation import (
    InsufficientDataError,
    iter_participant_folds,
    iter_single_stratified_folds,
    resolve_n_splits,
    sample_mask_for_participants,
)
from src.classification.evaluation.evaluation_artifact import (
    EvaluationArtifact,
    ModelFamilyResult,
)
from src.classification.evaluation.metrics import (
    aggregate_fold_metrics,
    compute_classification_metrics,
    compute_pr_curve,
    compute_roc_curve,
    ranking_score,
)
from src.classification.fusion.fusion_strategies import (
    available_fusion_names,
    create_fusion_strategy,
)
from src.classification.fusion.participant_pooling import pool_scores_by_participant
from src.classification.models.model_factory import available_model_names, create_model

_BASIS_KEYS = ["stride", "epoch"]


@dataclass
class FusionEvaluator:
    dataset: ClassificationDataset
    model_names: List[str] = field(default_factory=available_model_names)
    fusion_names: List[str] = field(default_factory=available_fusion_names)
    n_splits: int = 5
    n_repeats: int = 5
    inner_splits: int = 3
    random_state: int = 42
    fast_mode: bool = False
    verbose: bool = True

    def evaluate(self) -> EvaluationArtifact:
        common = self.dataset.common_participant_ids()
        if len(common) < 4:
            raise InsufficientDataError(
                "Need at least 4 participants present in both bases for fusion "
                f"evaluation; found {len(common)}."
            )
        labels_map = self.dataset.participant_labels()
        participant_ids = np.array(common, dtype=object)
        participant_labels = np.array([labels_map[p] for p in common], dtype=int)
        resolved_splits = resolve_n_splits(participant_labels, desired=self.n_splits)

        requires_inner = any(
            create_fusion_strategy(name).requires_training for name in self.fusion_names
        )

        model_results: List[ModelFamilyResult] = []
        for model_name in self.model_names:
            self._log(f"Evaluating model family: {model_name}")
            model_results.append(
                self._evaluate_family(
                    model_name=model_name,
                    participant_ids=participant_ids,
                    participant_labels=participant_labels,
                    n_splits=resolved_splits,
                    requires_inner=requires_inner,
                )
            )
            self._log(f"  completed {model_name}")

        ranking = self._build_ranking(model_results)
        return EvaluationArtifact(
            generated_at=datetime.now(timezone.utc).isoformat(),
            cv_config={
                "requested_n_splits": self.n_splits,
                "resolved_n_splits": resolved_splits,
                "n_repeats": self.n_repeats,
                "inner_splits": self.inner_splits,
                "random_state": self.random_state,
                "fast_mode": self.fast_mode,
            },
            participant_counts={
                "common": len(common),
                "faller": int(np.sum(participant_labels == 1)),
                "non_faller": int(np.sum(participant_labels == 0)),
                "stride_only": len(self.dataset.stride.participant_ids()),
                "epoch_only": len(self.dataset.epoch.participant_ids()),
            },
            sample_counts={
                "stride": self.dataset.stride.n_samples,
                "epoch": self.dataset.epoch.n_samples,
            },
            fusion_strategies=list(self.fusion_names),
            model_results=model_results,
            ranking=ranking,
        )

    def _evaluate_family(
        self,
        model_name: str,
        participant_ids: np.ndarray,
        participant_labels: np.ndarray,
        n_splits: int,
        requires_inner: bool,
    ) -> ModelFamilyResult:
        base_fold_metrics: Dict[str, List[Dict[str, float]]] = {k: [] for k in _BASIS_KEYS}
        fusion_fold_metrics: Dict[str, List[Dict[str, float]]] = {
            name: [] for name in self.fusion_names
        }
        fusion_oof: Dict[str, Dict[str, List[float]]] = {
            name: {"y": [], "p": []} for name in self.fusion_names
        }
        confusion_acc: Dict[str, np.ndarray] = {
            name: np.zeros(4, dtype=float) for name in self.fusion_names
        }
        best_params: Dict[str, Dict[str, object]] = {k: {} for k in _BASIS_KEYS}

        for train_idx, test_idx in iter_participant_folds(
            participant_labels, n_splits, self.n_repeats, self.random_state
        ):
            train_participants = participant_ids[train_idx].tolist()
            test_participants = participant_ids[test_idx].tolist()
            test_labels = participant_labels[test_idx]

            test_scores: Dict[str, np.ndarray] = {}
            for basis_key in _BASIS_KEYS:
                dataset = self.dataset.get_basis(_basis_from_key(basis_key))
                pooled, params = self._fit_predict_pooled(
                    model_name=model_name,
                    dataset=dataset,
                    train_participants=train_participants,
                    target_participants=test_participants,
                    enable_tuning=True,
                    fast_mode=self.fast_mode,
                )
                test_scores[basis_key] = pooled
                best_params[basis_key] = params
                base_fold_metrics[basis_key].append(
                    compute_classification_metrics(test_labels, pooled)
                )

            test_matrix = np.column_stack([test_scores[k] for k in _BASIS_KEYS])

            train_matrix: Optional[np.ndarray] = None
            train_fusion_labels: Optional[np.ndarray] = None
            if requires_inner:
                train_matrix, train_fusion_labels = self._inner_oof_matrix(
                    model_name=model_name,
                    train_participants=train_participants,
                    train_labels=participant_labels[train_idx],
                )

            for name in self.fusion_names:
                strategy = create_fusion_strategy(name, random_state=self.random_state)
                if strategy.requires_training and train_matrix is not None:
                    strategy.fit(train_matrix, train_fusion_labels)
                fused = strategy.predict_proba(test_matrix)
                fusion_fold_metrics[name].append(
                    compute_classification_metrics(test_labels, fused)
                )
                fusion_oof[name]["y"].extend(test_labels.tolist())
                fusion_oof[name]["p"].extend(fused.tolist())
                tn, fp, fn, tp = confusion_matrix(
                    test_labels, (fused >= 0.5).astype(int), labels=[0, 1]
                ).ravel()
                confusion_acc[name] += np.array([tn, fp, fn, tp], dtype=float)

        return ModelFamilyResult(
            model_name=model_name,
            base_results={
                key: aggregate_fold_metrics(base_fold_metrics[key]) for key in _BASIS_KEYS
            },
            fusion_results={
                name: aggregate_fold_metrics(fusion_fold_metrics[name])
                for name in self.fusion_names
            },
            roc_curves={
                name: compute_roc_curve(
                    np.array(fusion_oof[name]["y"]), np.array(fusion_oof[name]["p"])
                )
                for name in self.fusion_names
            },
            pr_curves={
                name: compute_pr_curve(
                    np.array(fusion_oof[name]["y"]), np.array(fusion_oof[name]["p"])
                )
                for name in self.fusion_names
            },
            confusion={
                name: {
                    "tn": float(confusion_acc[name][0]),
                    "fp": float(confusion_acc[name][1]),
                    "fn": float(confusion_acc[name][2]),
                    "tp": float(confusion_acc[name][3]),
                }
                for name in self.fusion_names
            },
            best_params=best_params,
        )

    def _fit_predict_pooled(
        self,
        model_name: str,
        dataset: BasisSampleDataset,
        train_participants: List[str],
        target_participants: List[str],
        enable_tuning: bool,
        fast_mode: bool,
    ) -> Tuple[np.ndarray, Dict[str, object]]:
        train_mask = sample_mask_for_participants(dataset.groups, train_participants)
        target_mask = sample_mask_for_participants(dataset.groups, target_participants)
        model = create_model(
            model_name,
            random_state=self.random_state,
            fast_mode=fast_mode,
            enable_tuning=enable_tuning,
        )
        try:
            model.fit(
                dataset.X[train_mask],
                dataset.y[train_mask],
                groups=dataset.groups[train_mask] if enable_tuning else None,
            )
            scores = model.predict_proba(dataset.X[target_mask])
        except Exception:
            scores = np.full(int(target_mask.sum()), np.nan, dtype=float)
        _, pooled = pool_scores_by_participant(
            dataset.groups[target_mask], scores, participant_order=target_participants
        )
        return pooled, dict(getattr(model, "best_params_", {}))

    def _inner_oof_matrix(
        self,
        model_name: str,
        train_participants: List[str],
        train_labels: np.ndarray,
    ) -> Tuple[np.ndarray, np.ndarray]:
        train_part_arr = np.array(train_participants, dtype=object)
        oof: Dict[str, np.ndarray] = {
            key: np.full(len(train_participants), np.nan, dtype=float)
            for key in _BASIS_KEYS
        }
        try:
            inner_splits = resolve_n_splits(train_labels, desired=self.inner_splits)
        except InsufficientDataError:
            return np.column_stack([oof[k] for k in _BASIS_KEYS]), train_labels

        for inner_train_idx, inner_val_idx in iter_single_stratified_folds(
            train_labels, inner_splits, self.random_state
        ):
            inner_train = train_part_arr[inner_train_idx].tolist()
            inner_val = train_part_arr[inner_val_idx].tolist()
            for basis_key in _BASIS_KEYS:
                dataset = self.dataset.get_basis(_basis_from_key(basis_key))
                pooled, _ = self._fit_predict_pooled(
                    model_name=model_name,
                    dataset=dataset,
                    train_participants=inner_train,
                    target_participants=inner_val,
                    enable_tuning=False,
                    fast_mode=True,
                )
                oof[basis_key][inner_val_idx] = pooled

        return np.column_stack([oof[k] for k in _BASIS_KEYS]), train_labels

    def _build_ranking(
        self, model_results: List[ModelFamilyResult]
    ) -> List[Dict[str, object]]:
        ranking: List[Dict[str, object]] = []
        for result in model_results:
            for fusion_name, metrics in result.fusion_results.items():
                ranking.append(
                    {
                        "model_name": result.model_name,
                        "fusion": fusion_name,
                        "roc_auc_mean": metrics.get("roc_auc_mean", float("nan")),
                        "pr_auc_mean": metrics.get("pr_auc_mean", float("nan")),
                        "balanced_accuracy_mean": metrics.get(
                            "balanced_accuracy_mean", float("nan")
                        ),
                        "score": ranking_score(metrics),
                    }
                )
        ranking.sort(key=lambda entry: entry["score"], reverse=True)
        return ranking

    def _log(self, message: str) -> None:
        if self.verbose:
            print(f"[classification] {message}")


def _basis_from_key(basis_key: str):
    from src.data_types.sample_basis.sample_basis import SampleBasis

    return SampleBasis.STRIDE if basis_key == "stride" else SampleBasis.EPOCH
