import argparse
from pathlib import Path
from typing import List

from src.database_manager.database_generator import DatabaseGenerator
from src.gait_features.config.extraction_backend import GaitExtractionBackendId
from src.gait_features.config.extraction_profile import ExtractionProfile
from src.gait_features.orchestration.feature_generation_run_log import (
    FeatureGenerationRunLog,
    FeatureGenerationRunSummary,
)
from src.gait_features.orchestration.gait_feature_dataset_orchestrator import (
    GaitFeatureDatasetOrchestrator,
)
from src.gait_features.pipeline.gait_extraction_pipeline import GaitExtractionPipeline
from src.identifiers.imu.imu_data_identifier import IMUDataIdentifier


def _parse_imu_ids(raw_value: str) -> List[IMUDataIdentifier]:
    entries = [item.strip() for item in raw_value.split(",") if item.strip()]
    return [IMUDataIdentifier(value) for value in entries]


def _parse_extraction_backend(raw_value: str) -> GaitExtractionBackendId:
    normalized = raw_value.strip().lower()
    for backend in GaitExtractionBackendId:
        if backend.value == normalized:
            return backend
    valid = ", ".join(item.value for item in GaitExtractionBackendId)
    raise ValueError(f"Unsupported extraction backend '{raw_value}'. Expected one of: {valid}.")


def _parse_extraction_profile(raw_value: str) -> ExtractionProfile:
    normalized = raw_value.strip().lower()
    for profile in ExtractionProfile:
        if profile.value == normalized:
            return profile
    valid = ", ".join(item.value for item in ExtractionProfile)
    raise ValueError(f"Unsupported extraction profile '{raw_value}'. Expected one of: {valid}.")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate gait RecordFeatures from IMU/User data indexed in SQLite."
    )
    parser.add_argument("--sqlite-db-path", type=Path, required=True)
    parser.add_argument(
        "--imu-output-dir",
        type=Path,
        default=None,
        help="Directory for IMU payload exports. Defaults to the SQLite DB parent directory.",
    )
    parser.add_argument(
        "--feature-output-dir",
        type=Path,
        default=None,
        help="Directory for feature payload exports. Defaults to the SQLite DB parent directory.",
    )
    parser.add_argument(
        "--instrument-spec-output-dir",
        type=Path,
        default=None,
        help=(
            "Directory for instrument-specification payload exports. "
            "Defaults to the SQLite DB parent directory."
        ),
    )
    parser.add_argument(
        "--imu-ids",
        type=str,
        default="",
        help="Optional comma-separated IMU IDs to process. Empty means all indexed IMUs.",
    )
    parser.add_argument(
        "--extraction-backend",
        type=str,
        default=GaitExtractionBackendId.SKDH.value,
        help="Gait extraction backend: skdh or mobgap.",
    )
    parser.add_argument(
        "--extraction-profile",
        type=str,
        default="",
        help=(
            "Extraction profile (free_living, treadmill, mobgap_healthy). "
            "Defaults from backend/treadmill flags when omitted."
        ),
    )
    parser.add_argument(
        "--treadmill-profile",
        action="store_true",
        help="Use treadmill SKDH profile for extraction (alias for --extraction-profile treadmill).",
    )
    parser.add_argument(
        "--epoch-window-seconds",
        type=float,
        default=8.0,
        help="Epoch sliding-window length in seconds (must be between 5 and 10).",
    )
    parser.add_argument(
        "--epoch-overlap-seconds",
        type=float,
        default=2.0,
        help="Epoch sliding-window overlap in seconds (> 0 and < window length).",
    )
    parser.add_argument(
        "--continue-on-error",
        action="store_true",
        help="Continue processing remaining IMUs when a record fails.",
    )
    parser.add_argument(
        "--rollback-on-partial-failure",
        action="store_true",
        help=(
            "If some IMUs succeed and others fail, delete newly generated feature "
            "records so the DB returns to its pre-run feature state."
        ),
    )
    parser.add_argument(
        "--rollback-last-run",
        action="store_true",
        help="Rollback feature records generated by the most recent extraction run.",
    )
    parser.add_argument(
        "--cleanup-features",
        action="store_true",
        help=(
            "Delete all feature records and feature relations while keeping IMU, user, "
            "and instrument-spec records."
        ),
    )
    return parser.parse_args()


def _build_pipeline(args: argparse.Namespace) -> GaitExtractionPipeline:
    backend = _parse_extraction_backend(args.extraction_backend)
    explicit_profile = (
        _parse_extraction_profile(args.extraction_profile)
        if args.extraction_profile.strip()
        else None
    )
    profile = ExtractionProfile.resolve(
        backend=backend,
        explicit_profile=explicit_profile,
        treadmill_profile=args.treadmill_profile,
    )
    return GaitExtractionPipeline.create(
        backend=backend,
        profile=profile,
        epoch_window_seconds=args.epoch_window_seconds,
        epoch_overlap_seconds=args.epoch_overlap_seconds,
    )


def _print_summary(summary: FeatureGenerationRunSummary) -> None:
    print(f"Run status: {summary.status}")
    print(f"Extraction backend: {summary.extraction_backend}")
    print(f"Extraction profile: {summary.extraction_profile}")
    print(f"Generated features: {len(summary.generated_feature_ids)}")
    if summary.generated_feature_ids:
        print("Generated feature IDs:")
        for feature_id in summary.generated_feature_ids:
            print(f"- {feature_id.value}")
    print(f"Failed IMUs: {len(summary.failed_imu_ids)}")
    if summary.failed_imu_ids:
        print("Failures:")
        for imu_id in summary.failed_imu_ids:
            print(f"- {imu_id.value}: {summary.errors_by_imu_id.get(imu_id.value, '')}")
    if summary.stride_failure_imu_ids:
        print(
            f"Stride-feature failures (all-NaN/no strides detected): "
            f"{len(summary.stride_failure_imu_ids)}"
        )
        for imu_id in summary.stride_failure_imu_ids:
            print(f"- {imu_id.value}")
    if summary.rollback_performed:
        print(
            "Rollback complete for this run. Removed "
            f"{len(summary.rolled_back_feature_ids)} feature record(s)."
        )


def main() -> None:
    args = parse_args()
    db_manager = DatabaseGenerator().generate_database(
        args.sqlite_db_path,
        imu_output_dir=args.imu_output_dir,
        feature_output_dir=args.feature_output_dir,
        instrument_spec_output_dir=args.instrument_spec_output_dir,
        # Cleanup and rollback exist to remove stale feature rows that validation rejects.
        validate=not (args.cleanup_features or args.rollback_last_run),
    )

    if args.cleanup_features:
        deleted = db_manager.cleanup_all_features(delete_payloads=True)
        print(f"Cleanup complete. Removed {len(deleted)} feature record(s).")
        return

    if args.rollback_last_run:
        deleted_count, deleted_ids = FeatureGenerationRunLog(db_manager).rollback_last_run()
        if deleted_count == 0:
            print("No rollback actions were performed for the last run.")
        else:
            print(f"Rollback complete. Removed {deleted_count} feature record(s):")
            for feature_id in deleted_ids:
                print(f"- {feature_id.value}")
        return

    orchestrator = GaitFeatureDatasetOrchestrator(
        db_manager=db_manager,
        pipeline=_build_pipeline(args),
    )
    if args.imu_ids.strip():
        summary = orchestrator.generate_for_imu_ids(
            imu_ids=_parse_imu_ids(args.imu_ids),
            continue_on_error=args.continue_on_error,
            rollback_on_partial_failure=args.rollback_on_partial_failure,
        )
    else:
        summary = orchestrator.generate_for_all_imu(
            continue_on_error=args.continue_on_error,
            rollback_on_partial_failure=args.rollback_on_partial_failure,
        )
    _print_summary(summary)


if __name__ == "__main__":
    main()
